from datetime import datetime, timezone

from sqlalchemy import JSON, Boolean, Column, DateTime, ForeignKey, Integer, String
from sqlalchemy.orm import relationship

from db import Base


def utcnow():
    return datetime.now(timezone.utc)


class User(Base):
    __tablename__ = 'users'
    user_id = Column(Integer, primary_key=True, index=True)
    username = Column(String(50), unique=True, nullable=False)
    password = Column(String(128), nullable=False)
    email = Column(String(255), unique=True, nullable=False)
    is_admin = Column(Boolean, nullable=False, default=False)

    settings = relationship(
        'UserSettings', back_populates='owner', uselist=False, cascade='all, delete-orphan'
    )
    matches = relationship('Match', back_populates='owner', cascade='all, delete-orphan')


class UserSettings(Base):
    """Tags, layout, default clip window and presets of one user, stored as one JSON document."""
    __tablename__ = 'user_settings'
    user_id = Column(Integer, ForeignKey('users.user_id', ondelete='CASCADE'), primary_key=True)
    data = Column(JSON, nullable=False)
    # Incremented on every write; clients send the version they started from (optimistic locking)
    version = Column(Integer, nullable=False, default=1)
    updated_at = Column(DateTime(timezone=True), nullable=False, default=utcnow, onupdate=utcnow)

    owner = relationship('User', back_populates='settings')


class Match(Base):
    """One recorded match. The id is generated by the client, so it is only unique per user."""
    __tablename__ = 'matches'
    user_id = Column(Integer, ForeignKey('users.user_id', ondelete='CASCADE'), primary_key=True)
    match_id = Column(String(36), primary_key=True)
    data = Column(JSON, nullable=False)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utcnow)
    updated_at = Column(DateTime(timezone=True), nullable=False, default=utcnow, onupdate=utcnow)

    owner = relationship('User', back_populates='matches')
